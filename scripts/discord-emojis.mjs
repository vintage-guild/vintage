#!/usr/bin/env node
// Upload the Vintage app's own Discord emoji (class, spec, and role icons) and write the
// name → id map the coordinator's cards read (modules/coordinator/src/domain/emoji-ids.ts).
// App emoji work in every server the bot is in, with no server emoji slots.
//
//   node --env-file=apps/api/.env.local scripts/discord-emojis.mjs          upload missing, write map
//   node --env-file=apps/api/.env.local scripts/discord-emojis.mjs --check  fail if the map is stale
//
// scripts/discord-emojis.json lists each emoji. A value is either a WoW icon name on Wowhead's
// CDN (downloaded once into the gitignored .vendor-src/wow-icons/; Blizzard's art is never
// committed) or `file:<repo path>` for one of our own images. Needs DISCORD_BOT_TOKEN and
// DISCORD_APP_ID; never prints the token.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CACHE = join(ROOT, '.vendor-src', 'wow-icons');
const MAP_FILE = join(ROOT, 'modules', 'coordinator', 'src', 'domain', 'emoji-ids.ts');
const API = 'https://discord.com/api/v10';
const check = process.argv.includes('--check');

const { $comment: _comment, ...manifest } = JSON.parse(
  readFileSync(join(ROOT, 'scripts', 'discord-emojis.json'), 'utf8'),
);
function requireEnv(name) {
  const value = process.env[name];
  if (!value) {
    console.error(
      `Set ${name} (e.g. node --env-file=apps/api/.env.local scripts/discord-emojis.mjs)`,
    );
    process.exit(1);
  }
  return value;
}
const token = requireEnv('DISCORD_BOT_TOKEN');
const appId = requireEnv('DISCORD_APP_ID');

async function discord(method, path, body) {
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(`${API}${path}`, {
      method,
      headers: {
        Authorization: `Bot ${token}`,
        'User-Agent': 'DiscordBot (https://github.com/vintage-guild/vintage, 0.0.0)',
        ...(body ? { 'Content-Type': 'application/json' } : {}),
      },
      body: body ? JSON.stringify(body) : undefined,
    });
    if (res.status === 429) {
      const wait = Number((await res.json()).retry_after ?? 1) * 1000;
      await new Promise((r) => setTimeout(r, wait));
      continue;
    }
    const data = res.status === 204 ? null : await res.json();
    if (!res.ok)
      throw new Error(`Discord ${method} ${path} failed with ${res.status}: ${data?.message}`);
    return data;
  }
  throw new Error(`Discord ${method} ${path} kept rate limiting`);
}

/** The image bytes and MIME type for one manifest entry, downloading WoW icons once. */
async function image(source) {
  if (source.startsWith('file:')) {
    const path = join(ROOT, source.slice(5));
    const type = { '.png': 'image/png', '.gif': 'image/gif' }[extname(path)] ?? 'image/jpeg';
    return { bytes: readFileSync(path), type };
  }
  const cached = join(CACHE, `${source}.jpg`);
  if (!existsSync(cached)) {
    const res = await fetch(`https://wow.zamimg.com/images/wow/icons/large/${source}.jpg`);
    if (!res.ok) throw new Error(`icon ${source} not found (${res.status})`);
    mkdirSync(dirname(cached), { recursive: true });
    writeFileSync(cached, Buffer.from(await res.arrayBuffer()));
  }
  return { bytes: readFileSync(cached), type: 'image/jpeg' };
}

function render(ids) {
  const lines = Object.entries(ids)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, id]) => `  ${name}: '${id}',`);
  return [
    '// Generated by scripts/discord-emojis.mjs. Do not edit; re-run the script.',
    "// The Vintage app's own Discord emoji: name → id. Used as <:name:id> in messages.",
    'export const EMOJI_IDS: Record<string, string> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

const existing = new Map(
  ((await discord('GET', `/applications/${appId}/emojis`)).items ?? []).map((e) => [e.name, e.id]),
);
const ids = {};
let uploaded = 0;
for (const [name, source] of Object.entries(manifest)) {
  if (existing.has(name)) {
    ids[name] = existing.get(name);
    continue;
  }
  if (check) {
    console.error(`Emoji ${name} is not uploaded yet; run scripts/discord-emojis.mjs`);
    process.exit(1);
  }
  const { bytes, type } = await image(source);
  const created = await discord('POST', `/applications/${appId}/emojis`, {
    name,
    image: `data:${type};base64,${bytes.toString('base64')}`,
  });
  ids[name] = created.id;
  uploaded++;
}

const next = render(ids);
const current = existsSync(MAP_FILE) ? readFileSync(MAP_FILE, 'utf8') : '';
if (check) {
  if (current !== next) {
    console.error('emoji-ids.ts is stale; run scripts/discord-emojis.mjs');
    process.exit(1);
  }
  console.log(`Emoji map is current (${Object.keys(ids).length} emoji).`);
} else {
  writeFileSync(MAP_FILE, next);
  console.log(`Uploaded ${uploaded}, ${Object.keys(ids).length} in the map: ${MAP_FILE}`);
}
